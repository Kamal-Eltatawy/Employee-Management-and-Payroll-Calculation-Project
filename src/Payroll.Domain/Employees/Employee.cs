using Payroll.Domain.Common;
using Payroll.Domain.Departments;
using Payroll.Domain.Payroll;

namespace Payroll.Domain.Employees;

/// <summary>Aggregate root (D16). Guards are the last line of defence; validators catch input errors first.</summary>
public sealed class Employee
{
    public const int FullNameMaxLength = 100;
    public const int EmailMaxLength = 254;
    public const int JobTitleMaxLength = 100;

    private readonly List<EmployeePayComponent> _payComponents = [];

    public Employee(
        string fullName, string email, string jobTitle, int departmentId, int taxSchemeId, DateOnly hireDate,
        decimal baseMonthlySalary, EmployeeStatus status, DateOnly today, DateTime utcNow)
    {
        FullName = Email = JobTitle = string.Empty;
        Apply(fullName, email, jobTitle, departmentId, taxSchemeId, hireDate, baseMonthlySalary, status, today);
        CreatedAtUtc = utcNow;
        UpdatedAtUtc = utcNow;
    }

    private Employee()
    {
        FullName = Email = JobTitle = string.Empty;
    }

    public int Id { get; private set; }

    public string FullName { get; private set; }

    /// <summary>Always stored trimmed and lower-cased.</summary>
    public string Email { get; private set; }

    public string JobTitle { get; private set; }

    public int DepartmentId { get; private set; }

    public Department? Department { get; private set; }

    /// <summary>Decides which payroll policies and which tax method apply (D53).</summary>
    public int TaxSchemeId { get; private set; }

    public TaxScheme? TaxScheme { get; private set; }

    public DateOnly HireDate { get; private set; }

    public decimal BaseMonthlySalary { get; private set; }

    public EmployeeStatus Status { get; private set; }

    public IReadOnlyCollection<EmployeePayComponent> PayComponents => _payComponents.AsReadOnly();

    /// <summary>Concurrency token (D12), generated by the database.</summary>
    public byte[] RowVersion { get; private set; } = [];

    public DateTime CreatedAtUtc { get; private set; }

    public DateTime UpdatedAtUtc { get; private set; }

    /// <summary>Not null means soft deleted (D5).</summary>
    public DateTime? DeletedAtUtc { get; private set; }

    public static string NormalizeEmail(string email) => email.Trim().ToLowerInvariant();

    public void UpdateDetails(
        string fullName, string email, string jobTitle, int departmentId, int taxSchemeId, DateOnly hireDate,
        decimal baseMonthlySalary, EmployeeStatus status, DateOnly today, DateTime utcNow)
    {
        Apply(fullName, email, jobTitle, departmentId, taxSchemeId, hireDate, baseMonthlySalary, status, today);
        UpdatedAtUtc = utcNow;
    }

    /// <summary>Replaces the assigned pay components. Existing rows are kept (amount updated) when the type stays.</summary>
    public void SetPayComponents(IReadOnlyCollection<PayComponentAssignment> assignments, DateTime utcNow)
    {
        if (assignments.GroupBy(a => a.PayComponentTypeId).Any(group => group.Count() > 1))
        {
            throw new DomainException("A pay component type can be assigned only once.");
        }

        foreach (var assignment in assignments)
        {
            Guard.PositiveId(assignment.PayComponentTypeId, "Pay component type");
            Guard.Positive(assignment.Amount, "Pay component amount");
        }

        var typeIds = assignments.Select(a => a.PayComponentTypeId).ToHashSet();
        _payComponents.RemoveAll(component => !typeIds.Contains(component.PayComponentTypeId));

        foreach (var assignment in assignments)
        {
            var existing = _payComponents.Find(c => c.PayComponentTypeId == assignment.PayComponentTypeId);
            if (existing is null)
            {
                _payComponents.Add(new EmployeePayComponent(assignment.PayComponentTypeId, assignment.Amount));
            }
            else
            {
                existing.ChangeAmount(assignment.Amount);
            }
        }

        UpdatedAtUtc = utcNow;
    }

    public void MarkDeleted(DateTime utcNow)
    {
        if (DeletedAtUtc is not null)
        {
            throw new DomainException("The employee is already deleted.");
        }

        DeletedAtUtc = utcNow;
        UpdatedAtUtc = utcNow;
    }

    /// <summary>Spec §11.3 checks 4 and 5: the employee must be Active and the month must not be before the hire month.</summary>
    public void EnsureEligibleForPayslip(PayrollMonth month)
    {
        if (Status != EmployeeStatus.Active)
        {
            throw new DomainException("Employee is inactive.");
        }

        var hireMonth = PayrollMonth.From(HireDate);
        if (month < hireMonth)
        {
            throw new DomainException($"Employee was hired in {hireMonth}.");
        }
    }

    private void Apply(
        string fullName, string email, string jobTitle, int departmentId, int taxSchemeId, DateOnly hireDate,
        decimal baseMonthlySalary, EmployeeStatus status, DateOnly today)
    {
        if (hireDate > today)
        {
            throw new DomainException("Hire date cannot be in the future.");
        }

        FullName = Guard.RequiredText(fullName, FullNameMaxLength, "Full name");
        Email = NormalizeEmail(Guard.RequiredText(email, EmailMaxLength, nameof(Email)));
        JobTitle = Guard.RequiredText(jobTitle, JobTitleMaxLength, "Job title");
        DepartmentId = Guard.PositiveId(departmentId, "Department");
        TaxSchemeId = Guard.PositiveId(taxSchemeId, "Tax scheme");
        HireDate = hireDate;
        BaseMonthlySalary = Guard.Positive(baseMonthlySalary, "Base monthly salary");
        Status = Guard.Defined(status, nameof(Status));
    }
}
